    def test_bachelors_requires_skills(self):
        """Verify Bachelor's users still need at least one skill."""
        response = self.client.post(
            "/api/analyze-career",
            data=json.dumps({
                "full_name": "Sara Ahmad",
                "education": "Undergraduate",
                "skills": [],
                "answers": {},
                "questions": []
            }),
            content_type="application/json"
        )
        self.assertEqual(response.status_code, 400)
        data = json.loads(response.data)
        self.assertEqual(data["status"], "error")
        self.assertIn("Please add at least one skill with a skill level.", data["message"])

    def test_matric_analysis_endpoint_and_results(self):
        """Verify Matric analysis returns study-path data and renders the Matric results view."""
        import app as app_module
        original = app_module.analyze_matric_study_path
        app_module.analyze_matric_study_path = lambda profile, questions, answers: {
            "is_matric": True,
            "recommended_path": {
                "title": "ICS",
                "reason": "You enjoy working with computers and scored well in Computer Science."
            },
            "other_options": [
                {"title": "FSc Pre-Engineering", "reason": "Your Maths and Physics marks are strong."},
                {"title": "ICom", "reason": "You also showed interest in business-related work."}
            ],
            "future_careers": [
                {"title": "Software Engineer", "description": "Build apps, websites, and software."},
                {"title": "Web Developer", "description": "Create and maintain websites."}
            ],
            "roadmap": ["Matric", "ICS", "BS Computer Science", "Software Engineer"],
            "career_profile": {
                "analytical": 0, "technical": 0, "creative": 0,
                "social": 0, "leadership": 0, "research": 0, "practical": 0
            }
        }
        try:
            response = self.client.post(
                "/api/analyze-career",
                data=json.dumps({
                    "full_name": "Ali Khan",
                    "education": "Matric",
                    "skills": [],
                    "answers": {"q1": "a"},
                    "questions": [{"id": "q1", "question": "Q", "options": [{"value": "a", "label": "A"}]}],
                    "matric_group": "Science",
                    "percentage": "85"
                }),
                content_type="application/json"
            )
            self.assertEqual(response.status_code, 200)
            data = json.loads(response.data)
            self.assertEqual(data["status"], "success")
            self.assertTrue(data["data"]["is_matric"])
            self.assertEqual(data["data"]["recommended_path"]["title"], "ICS")

            # Verify the Matric-specific error about skills is NOT returned
            self.assertNotIn(b"Please add at least one skill with a skill level.", response.data)

            # Verify the results page renders the Matric-specific template
            results_response = self.client.get("/results")
            self.assertEqual(results_response.status_code, 200)
            self.assertIn(b"Your Recommended Intermediate Path", results_response.data)
            self.assertIn(b"Student Profile Summary", results_response.data)
            self.assertIn(b"Education Path Analysis", results_response.data)
            self.assertIn(b"ICS", results_response.data)
            self.assertIn(b"Software Engineer", results_response.data)
        finally:
            app_module.analyze_matric_study_path = original


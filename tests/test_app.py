"""
Unit and Integration Tests for AI Career Guide
Tests all routes, score calculations, fallback mechanisms, and API endpoints.
"""

import unittest
import json
from app import app
from services.ai_service import generate_ai_preference_profile


class TestAICareerGuide(unittest.TestCase):

    def setUp(self):
        self.client = app.test_client()
        self.client.testing = True
        # Clear the global results cache so tests do not leak state
        import app as app_module
        app_module.GLOBAL_RESULTS_CACHE.clear()

    def test_landing_page(self):
        """Verify the landing page loads successfully."""
        response = self.client.get("/")
        self.assertEqual(response.status_code, 200)
        self.assertIn(b"AI Career Guide", response.data)
        self.assertIn(b"Discover your strengths", response.data)
        self.assertIn(b"How It Works", response.data)

    def test_assessment_page(self):
        """Verify the multi-step assessment page loads."""
        response = self.client.get("/assessment")
        self.assertEqual(response.status_code, 200)
        self.assertIn(b"Career Assessment", response.data)
        self.assertIn(b"Education Level", response.data)
        self.assertIn(b"Tell Us About Yourself", response.data)

    def test_results_page_requires_profile(self):
        """Verify results do not depend on a sample profile."""
        response = self.client.get("/results")
        self.assertEqual(response.status_code, 302)
        self.assertIn("/assessment", response.headers["Location"])

    def test_career_detail_requires_profile(self):
        """Verify career details do not depend on a sample profile."""
        response = self.client.get("/career/machine-learning-engineer")
        self.assertEqual(response.status_code, 302)
        self.assertIn("/assessment", response.headers["Location"])

    def test_dynamic_question_requires_configured_ai(self):
        """Verify dynamic questions are served by the AI endpoint rather than static content."""
        response = self.client.post(
            "/api/generate-question",
            data=json.dumps({"question_number": 1, "profile": {}, "previous_questions": [], "previous_answers": {}}),
            content_type="application/json"
        )
        self.assertIn(response.status_code, (200, 503))

    def test_calculate_profile_endpoint(self):
        """Verify the preference profile is generated by the AI service."""
        import app as app_module
        original = app_module.generate_ai_preference_profile
        app_module.generate_ai_preference_profile = lambda profile, questions, answers: {
            "analytical": 70, "technical": 80, "creative": 55, "social": 45,
            "leadership": 50, "research": 65, "practical": 60
        }
        try:
            response = self.client.post(
                "/api/calculate-profile",
                data=json.dumps({
                    "profile": {"skills": [{"name": "Python", "level": "Intermediate"}]},
                    "answers": {"q1": "a"},
                    "questions": [{"id": "q1", "question": "Example", "options": [{"value": "a", "label": "Example"}]}]
                }),
                content_type="application/json"
            )
            self.assertEqual(response.status_code, 200)
            data = json.loads(response.data)
            self.assertEqual(data["status"], "success")
            self.assertIn("technical", data["career_profile"])
        finally:
            app_module.generate_ai_preference_profile = original

    def test_health_endpoint(self):
        """Verify healthcheck endpoint."""
        response = self.client.get("/health")
        self.assertEqual(response.status_code, 200)
        data = json.loads(response.data)
        self.assertEqual(data["status"], "healthy")

